// Regenerate from the unmodified @icon-park/svg 1.4.2 package, extracted locally.
// Usage: node modules/ui_controls/icons/generate.cjs /path/to/package
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const upstream = path.resolve(process.argv[2] || '');
const packageInfo = JSON.parse(fs.readFileSync(path.join(upstream, 'package.json'), 'utf8'));
if (packageInfo.name !== '@icon-park/svg' || packageInfo.version !== '1.4.2')
    throw new Error('Expected the official @icon-park/svg 1.4.2 package');
const icons = {
    home: 'Home', history: 'History', user: 'User', model: 'Cpu', audio: 'SoundWave',
    'arrow-right': 'ArrowRight', plus: 'Plus', check: 'Check', close: 'Close',
    'chevron-left': 'Left', 'chevron-right': 'Right', search: 'Search', file: 'FileText',
    upload: 'UploadOne', download: 'Download', trash: 'Delete', edit: 'Edit',
    play: 'PlayOne', pause: 'Pause', stop: 'Square', collapse: 'Up', expand: 'Down',
    grip: 'Drag', clock: 'Time', headphones: 'Headset', mic: 'Voice',
    settings: 'SettingConfig', alert: 'Attention', eye: 'PreviewOpen', bolt: 'Lightning', info: 'Info'
};
const notice = 'IconPark — Copyright 2019-present Bytedance Inc. Apache-2.0.\n'
    + 'Generated from official @icon-park/svg 1.4.2 with outline theme, 48px size,\n'
    + '4-unit rounded strokes and #18181b foreground. Geometry is unchanged.\n'
    + 'AppIcon replaces only the foreground color at runtime.\n';
const data = {};
const sourceFiles = {};
for (const [alias, exportName] of Object.entries(icons)) {
    const input = path.join(upstream, 'lib/icons', exportName + '.js');
    const renderer = require(input).default;
    const svg = renderer({theme:'outline', size:48, strokeWidth:4,
        strokeLinecap:'round', strokeLinejoin:'round', fill:'#18181b'});
    data[alias] = svg;
    const document = svg.replace('?>', '?>\n<!-- ' + notice.replace(/\n/g, ' ') + ' -->\n') + '\n';
    fs.writeFileSync(path.join(__dirname, alias + '.svg'), document);
    sourceFiles[alias] = {icon:exportName, source:'lib/icons/' + exportName + '.js',
        sha256:crypto.createHash('sha256').update(fs.readFileSync(input)).digest('hex')};
}
fs.copyFileSync(path.join(upstream, 'LICENSE'), path.join(__dirname, 'LICENSE'));
fs.writeFileSync(path.join(__dirname, 'NOTICE'), notice);
fs.writeFileSync(path.join(__dirname, 'SOURCE.json'), JSON.stringify({
    package:'@icon-park/svg', version:'1.4.2',
    website:'https://iconpark.oceanengine.com/official',
    repository:'https://github.com/bytedance/IconPark',
    gitHead:packageInfo.gitHead,
    archive:'https://registry.npmjs.org/@icon-park/svg/-/svg-1.4.2.tgz',
    archiveSha256:'fbd548c2d6c3830a56828c9cf09787d61ce2a74a4f398919059e111de17c504b',
    configuration:{theme:'outline',size:48,strokeWidth:4,strokeLinecap:'round',strokeLinejoin:'round',fill:'#18181b'},
    icons:sourceFiles
}, null, 2) + '\n');
fs.writeFileSync(path.join(__dirname, '../IconParkData.js'),
    '.pragma library\n\n// Generated by icons/generate.cjs from official IconPark SVG output.\n'
    + '// Copyright 2019-present Bytedance Inc. Apache-2.0; see icons/LICENSE and NOTICE.\n'
    + 'var svgByName = ' + JSON.stringify(data, null, 4) + ';\n\n'
    + 'function source(name, red, green, blue) {\n'
    + '    var svg = svgByName[name];\n'
    + '    if (!svg) return "";\n'
    + '    var color = "rgb(" + Math.round(red * 255) + "," + Math.round(green * 255) + "," + Math.round(blue * 255) + ")";\n'
    + '    return "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg.replace(/#18181b/g, color));\n'
    + '}\n');
